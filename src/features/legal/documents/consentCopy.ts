/**
 * The release switches the in-app drafts follow (15 §10, the R2-FE-01 release act).
 * A switch is on when its document is shippable (`final`, marker-free):
 * - `privacy`, the wired Privacy voice variant. Published (the ElevenLabs
 *   text, I-71), it releases `warning.voice`, `call.screen.privacyNote` and
 *   the docs record line for every user.
 * - `consentV2`, the `voice-v2` consent copy. Final (R1-LEG-01 closed, I-71),
 *   it releases the consent `noRecordings` line, shown next to the `voice-v2`
 *   copy only (13 §5.8 "With `voice-v2`").
 */
export interface InAppCopySwitches {
    privacy: LegalDraft<PrivacyVoiceCopy>
    consentV2: LegalDraft<ConsentCopy>
}

/**
 * The shipped switches: both on since I-71 (2026-10-14). Each in-app line
 * still waits for its own draft to be marked final.
 */
export const IN_APP_COPY_SWITCHES: Readonly<InAppCopySwitches> = Object.freeze({
    privacy: PRIVACY_VOICE_VARIANTS[PRIVACY_VOICE_VARIANT],
    consentV2: CONSENT_COPY['voice-v2'],
})

/** The drafts the Privacy flip releases for everyone; `consentNoRecordings` rides `voice-v2` instead. */
export const PRIVACY_FLIP_DRAFT_IDS: readonly InAppCopyDraftId[] = Object.freeze(['warningVoice', 'callPrivacyNote', 'docsVoiceRecord'])

type InAppCopyDrafts = Readonly<Record<InAppCopyDraftId, LegalDraft<InAppCopyDraft>>>

/**
 * Whether a draft replaces its locale key: the draft is shippable (`final`,
 * marker-free) AND its release switch is on. Either half alone changes
 * nothing, so a partial release act keeps today's copy.
 */
export function isInAppCopyReleased(
    id: InAppCopyDraftId,
    switches: Readonly<InAppCopySwitches> = IN_APP_COPY_SWITCHES,
    drafts: InAppCopyDrafts = IN_APP_COPY_DRAFTS,
): boolean {
    if (!isShippable(drafts[id])) return false
    return id === 'consentNoRecordings' ? isShippable(switches.consentV2) : isShippable(switches.privacy)
}

/** The released draft text of `id`, or null while today's locale copy stands. */
export function releasedInAppCopy(
    id: InAppCopyDraftId,
    language: LegalLanguage,
    switches: Readonly<InAppCopySwitches> = IN_APP_COPY_SWITCHES,
    drafts: InAppCopyDrafts = IN_APP_COPY_DRAFTS,
): string | null {
    return isInAppCopyReleased(id, switches, drafts) ? drafts[id][language].text : null
}

/**
 * The released Privacy-flip lines as a locale overlay, nested by each draft's
 * locale key (`{ warning: { voice } }`, ...); empty while none is released.
 */
export function inAppCopyOverlay(
    language: LegalLanguage,
    switches: Readonly<InAppCopySwitches> = IN_APP_COPY_SWITCHES,
    drafts: InAppCopyDrafts = IN_APP_COPY_DRAFTS,
): Record<string, unknown> {
    const overlay: Record<string, unknown> = {}
    for (const id of PRIVACY_FLIP_DRAFT_IDS) {
        const text = releasedInAppCopy(id, language, switches, drafts)
        if (text !== null) setPath(overlay, drafts[id].id.split('.'), text)
    }
    return overlay
}

function setPath(target: Record<string, unknown>, path: readonly string[], value: string): void {
    let node = target
    for (const part of path.slice(0, -1)) {
        const next = node[part]
        node = typeof next === 'object' && next !== null ? (next as Record<string, unknown>) : (node[part] = {}) as Record<string, unknown>
    }
    node[path[path.length - 1]] = value
}

/** The i18n languages the in-app legal lines ship in (en, es and their regional tags, 13 §5.8). */
function shipsInAppCopy(language: string): boolean {
    return /^(en|es)(-|$)/i.test(language.trim())
}

/**
 * `overlay` laid over `base` without writing to `base`: new objects along the
 * overlay's paths, untouched siblings shared by reference.
 */
function overlaid(base: unknown, overlay: unknown): unknown {
    if (typeof overlay !== 'object' || overlay === null) return overlay
    const source = typeof base === 'object' && base !== null ? (base as Record<string, unknown>) : {}
    const out: Record<string, unknown> = { ...source }
    for (const [key, value] of Object.entries(overlay as Record<string, unknown>)) out[key] = overlaid(source[key], value)
    return out
}

/**
 * Wires the Privacy-flip lines into an i18next instance (once, at app start in
 * src/app/i18n): bundles already present get the overlay now, and every
 * language loaded later (es is lazy) gets it as it loads, so `t()` serves the
 * released text wherever the key is read (first-run warning, call screen, docs
 * and the app assistant). While nothing is released it does nothing at all (no
 * listener, no bundle write): the locale copy stays byte-identical. Returns
 * whether it installed.
 *
 * - Only en and es get the lines; any other locale keeps its own strings
 *   (the legal copy ships in en and es only, and is never shown in another
 *   language's bundle).
 * - Copy-on-write: i18next keeps the bundled `en` module and the lazy `es`
 *   module by reference, so each top-level branch the overlay touches is
 *   rebuilt and swapped in shallowly; the exported locale objects are never
 *   written to.
 */
export function installInAppCopyRelease(
    i18n: Pick<I18n, 'addResourceBundle' | 'getResourceBundle' | 'hasResourceBundle' | 'on'>,
    switches: Readonly<InAppCopySwitches> = IN_APP_COPY_SWITCHES,
    drafts: InAppCopyDrafts = IN_APP_COPY_DRAFTS,
): boolean {
    if (!PRIVACY_FLIP_DRAFT_IDS.some((id) => isInAppCopyReleased(id, switches, drafts))) return false
    const apply = (language: string) => {
        if (!shipsInAppCopy(language)) return
        const bundle = (i18n.getResourceBundle(language, 'translation') ?? {}) as Record<string, unknown>
        const branches: Record<string, unknown> = {}
        for (const [top, branch] of Object.entries(inAppCopyOverlay(legalLanguage(language), switches, drafts))) {
            branches[top] = overlaid(bundle[top], branch)
        }
        i18n.addResourceBundle(language, 'translation', branches, false, true)
    }
    for (const language of ['en', 'es']) {
        if (i18n.hasResourceBundle(language, 'translation')) apply(language)
    }
    i18n.on('loaded', (loaded: { [language: string]: { [namespace: string]: boolean } }) => {
        for (const language of Object.keys(loaded ?? {})) apply(language)
    })
    return true
}
