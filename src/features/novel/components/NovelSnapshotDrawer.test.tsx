import { snapshotNoteReaders } from '@/test/fixtures/storySnapshotNotes'
import { act,fireEvent,render,screen,waitFor,within } from '@testing-library/react'
import { beforeEach,expect,it,vi } from 'vitest'
import type { StorySnapshotPage } from '@/shared'
import type { StorySnapshotSource } from '../hooks/useSnapshotSource'
import { snapshotComparison,snapshotPage,snapshotPreview,snapshotStory,snapshotView,snapshotOperation,snapshotSummary,snapshotRestorePreview } from '@/test/fixtures/storySnapshots'
import { NovelSnapshotDrawer } from './NovelSnapshotDrawer'

const before=vi.fn(),operate=vi.fn(),recover=vi.fn()
let source:StorySnapshotSource
const props=()=>({source,open:true,onClose:vi.fn(),structureRevision:5,readOnly:false,busy:false,beforeWrite:before,operate,recover})
beforeEach(()=>{
    vi.clearAllMocks();before.mockResolvedValue(true);operate.mockResolvedValue(snapshotStory(true));recover.mockResolvedValue(snapshotStory(true))
    source={...snapshotNoteReaders,key:'author:workspace:story-1',isCurrent:()=>true,list:vi.fn().mockResolvedValue(snapshotPage()),preview:vi.fn().mockResolvedValue(snapshotPreview()),compare:vi.fn().mockResolvedValue(snapshotComparison()),scene:vi.fn().mockResolvedValue(snapshotView()),currentScene:vi.fn().mockResolvedValue(snapshotStory(true).chapters[0].scenes[0]),restorePreview:vi.fn().mockResolvedValue(snapshotRestorePreview())}
})
it('requires both save/review barriers and sends the frozen reviewed name, note and source once',async()=>{
    before.mockResolvedValueOnce(false).mockResolvedValueOnce(true).mockResolvedValueOnce(false).mockResolvedValue(true)
    render(<NovelSnapshotDrawer {...props()}/>)
    fireEvent.change(screen.getByLabelText('Snapshot name'),{target:{value:'A completed draft'}})
    fireEvent.change(screen.getByLabelText('Milestone note (optional)'),{target:{value:'  Keep this note exactly.\n'}})
    fireEvent.click(screen.getByRole('button',{name:'Review snapshot'}))
    await screen.findByRole('alert');expect(source.preview).not.toHaveBeenCalled()
    await waitFor(()=>expect(screen.getByRole('button',{name:'Review snapshot'})).toBeEnabled())
    fireEvent.click(screen.getByRole('button',{name:'Review snapshot'}))
    const review=await screen.findByRole('dialog',{name:'Review manuscript snapshot'})
    expect(within(review).getByText('Parts: 0 · chapters: 1 · scenes: 1 · pins: 1')).toBeInTheDocument()
    fireEvent.click(within(review).getByRole('button',{name:'Save snapshot'}))
    await within(review).findByRole('alert');expect(operate).not.toHaveBeenCalled()
    await waitFor(()=>expect(within(review).getByRole('button',{name:'Save snapshot'})).toBeEnabled())
    fireEvent.click(within(review).getByRole('button',{name:'Save snapshot'}));fireEvent.click(within(review).getByRole('button',{name:'Save snapshot'}))
    await waitFor(()=>expect(operate).toHaveBeenCalledOnce())
    expect(operate).toHaveBeenCalledWith({op:'create_snapshot',title:'A completed draft',note:'  Keep this note exactly.\n',sourceStructureRevision:5,expectedSourceVersion:'c'.repeat(64),sourceAnnotationRevision:6})
    expect(before).toHaveBeenCalledTimes(4)
})
it('compares frozen prose, notes and pin versions with the saved current scene without writing',async()=>{
    render(<NovelSnapshotDrawer {...props()}/>)
    fireEvent.click(await screen.findByRole('button',{name:'First complete draft'}))
    const comparison=await screen.findByRole('region',{name:'Snapshot comparison'})
    expect(within(comparison).getByText('Text changed')).toBeInTheDocument()
    fireEvent.click(within(comparison).getByRole('button',{name:'Chapter 1 · At the gate'}))
    const reading=await screen.findByRole('region',{name:'Saved scene comparison'})
    expect(within(reading).getByText('The original gate held.')).toBeInTheDocument()
    expect(within(reading).getByText('The current gate opens.')).toBeInTheDocument()
    expect(within(reading).getByText(/Original scene notes/)).toBeInTheDocument()
    expect(within(reading).getByText(/Mira · Version 3 · Enabled/)).toBeInTheDocument()
    expect(source.scene).toHaveBeenCalledWith(3,expect.objectContaining({id:'scene-1',revision:2,contentHash:'b'.repeat(64)}),'d'.repeat(64))
    expect(operate).not.toHaveBeenCalled()
})
it('keeps frozen text readable while rejecting a newer current scene at comparison time',async()=>{
    source.currentScene=vi.fn().mockResolvedValue({...snapshotStory(true).chapters[0].scenes[0],revision:4})
    render(<NovelSnapshotDrawer {...props()}/>)
    fireEvent.click(await screen.findByRole('button',{name:'First complete draft'}))
    fireEvent.click(await screen.findByRole('button',{name:'Chapter 1 · At the gate'}))
    const reading=await screen.findByRole('region',{name:'Saved scene comparison'})
    expect(within(reading).getByText(/current scene changed after comparison/)).toBeInTheDocument()
    expect(within(reading).getByText('The original gate held.')).toBeInTheDocument()
    expect(within(reading).queryByText('The current gate opens.')).not.toBeInTheDocument()
})
it('locks an uncertain capture to its original empty note and can recover its receipt while archived',async()=>{
    const p=props(),view=render(<NovelSnapshotDrawer {...p}/>)
    fireEvent.change(screen.getByLabelText('Milestone note (optional)'),{target:{value:'Another unsent note'}})
    const pending=snapshotOperation()
    view.rerender(<NovelSnapshotDrawer {...p} readOnly pendingOperation={pending}/>)
    expect(screen.getByLabelText('Snapshot name')).toHaveValue(pending.title)
    expect(screen.getByLabelText('Snapshot name')).toBeDisabled()
    expect(screen.getByLabelText('Milestone note (optional)')).toHaveValue('')
    fireEvent.click(screen.getByRole('button',{name:'Recover request'}))
    await waitFor(()=>expect(recover).toHaveBeenCalledOnce())
    expect(operate).not.toHaveBeenCalled();expect(source.preview).not.toHaveBeenCalled()
})
it('preserves unsent capture fields across closing the browser but clears them across owners',async()=>{
    const p=props(),view=render(<NovelSnapshotDrawer {...p}/>)
    fireEvent.change(screen.getByLabelText('Snapshot name'),{target:{value:'Private milestone'}})
    view.rerender(<NovelSnapshotDrawer {...p} open={false}/>)
    view.rerender(<NovelSnapshotDrawer {...p}/>)
    expect(screen.getByLabelText('Snapshot name')).toHaveValue('Private milestone')
    view.rerender(<NovelSnapshotDrawer {...p} source={{...source,key:'another-author:workspace:story-1'}}/>)
    expect(screen.getByLabelText('Snapshot name')).toHaveValue('')
})
it('ignores late snapshot reads from a closed or replaced owner scope',async()=>{
    let finish!:(value:StorySnapshotPage)=>void
    source.list=vi.fn(()=>new Promise<StorySnapshotPage>((resolve)=>{finish=resolve}))
    const p=props(),view=render(<NovelSnapshotDrawer {...p}/>)
    const next={...source,key:'another-author:workspace:story-2',list:vi.fn().mockResolvedValue(snapshotPage({storyId:'story-2',items:[snapshotSummary({storyId:'story-2',name:'A different book'})]}))}
    view.rerender(<NovelSnapshotDrawer {...p} source={next}/>)
    await screen.findByRole('button',{name:'A different book'})
    await act(async()=>{finish(snapshotPage({items:[snapshotSummary({name:'Former private title'})]}))})
    expect(screen.queryByText('Former private title')).not.toBeInTheDocument()
})
it('requires an explicit refreshed capture review after the source changed',async()=>{
    const p=props(),clear=vi.fn(),view=render(<NovelSnapshotDrawer {...p} clearOperationError={clear}/>)
    fireEvent.change(screen.getByLabelText('Snapshot name'),{target:{value:'Same milestone'}})
    fireEvent.click(screen.getByRole('button',{name:'Review snapshot'}))
    const review=await screen.findByRole('dialog',{name:'Review manuscript snapshot'})
    view.rerender(<NovelSnapshotDrawer {...p} clearOperationError={clear} operationError="STORY_SNAPSHOT_SOURCE_CHANGED"/>)
    expect(within(review).queryByRole('button',{name:'Save snapshot'})).not.toBeInTheDocument()
    source.preview=vi.fn().mockResolvedValue({...snapshotPreview(),sourceVersion:'e'.repeat(64)})
    fireEvent.click(within(review).getByRole('button',{name:'Refresh review'}))
    await waitFor(()=>expect(source.preview).toHaveBeenCalledOnce())
    view.rerender(<NovelSnapshotDrawer {...p} clearOperationError={clear}/>)
    await waitFor(()=>expect(within(review).getByRole('button',{name:'Save snapshot'})).toBeEnabled())
    fireEvent.click(within(review).getByRole('button',{name:'Save snapshot'}))
    await waitFor(()=>expect(operate).toHaveBeenCalledWith(expect.objectContaining({title:'Same milestone',expectedSourceVersion:'e'.repeat(64)})))
})
it('retains over-limit Unicode names and notes rather than silently truncating author input',()=>{
    render(<NovelSnapshotDrawer {...props()}/>)
    const name='✨'.repeat(256),note='Note '.repeat(401)
    fireEvent.change(screen.getByLabelText('Snapshot name'),{target:{value:name}})
    fireEvent.change(screen.getByLabelText('Milestone note (optional)'),{target:{value:note}})
    expect(screen.getByLabelText('Snapshot name')).toHaveValue(name)
    expect(screen.getByLabelText('Milestone note (optional)')).toHaveValue(note)
    expect(screen.getByRole('button',{name:'Review snapshot'})).toBeDisabled()
    expect(before).not.toHaveBeenCalled();expect(operate).not.toHaveBeenCalled()
})
